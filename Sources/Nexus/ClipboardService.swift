import AppKit
import ApplicationServices
import NexusCore

/// Pasteboard watcher + storage glue + paste synthesis.
final class ClipboardService {
    static let shared = ClipboardService()

    let store: ClipboardStore
    private let imagesDir: URL
    private var lastChange = NSPasteboard.general.changeCount
    private var ownWrites = Set<Int>()
    private var timers: [Timer] = []
    private var askedForAccessibility = false
    /// Content hashes of secret snippet values: never recorded in history (and scrubbed if already there).
    private var blockedHashes = Set<String>()

    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Nexus")
        imagesDir = base.appendingPathComponent("images")
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        store = ClipboardStore(path: base.appendingPathComponent("clipboard.db").path)
    }

    func start() {
        purge()
        let poll = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.tick() }
        let hourly = Timer(timeInterval: 3600, repeats: true) { [weak self] _ in self?.purge() }
        RunLoop.main.add(poll, forMode: .common)
        RunLoop.main.add(hourly, forMode: .common)
        timers = [poll, hourly]
    }

    /// Remember a secret value (by hash) so it's never recorded, and scrub it from history if already there.
    /// Fed whenever a secret is saved, pasted or revealed, so Nexus never has to read the Keychain at launch.
    func block(value: String) {
        let h = ClipDraft.hash(Data(value.utf8))
        blockedHashes.insert(h)
        store.delete(hash: h)
    }

    // MARK: capture

    private func tick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if ownWrites.remove(lastChange) != nil { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        let bundle = front?.bundleIdentifier ?? ""
        guard !Settings.shared.data.clipboardExcludedApps.contains(bundle) else { return }

        var draft: ClipDraft?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let text = urls.map(\.path).joined(separator: "\n")
            draft = ClipDraft(kind: .file, text: text, hash: ClipDraft.hash(Data(("file:" + text).utf8)))
        } else if let png = Self.pngData(from: pb) {
            draft = imageDraft(png)
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, s.utf8.count < 10_000_000 {
            let isURL = !s.contains(where: \.isWhitespace) && (URL(string: s).map { $0.scheme?.hasPrefix("http") == true && $0.host != nil } ?? false)
            let hash = ClipDraft.hash(Data(s.utf8))
            guard !blockedHashes.contains(hash) else { return }
            var d = ClipDraft(kind: isURL ? .url : .text, text: s, hash: hash)
            d.chars = s.count
            d.words = s.split(whereSeparator: \.isWhitespace).count
            if let rtf = pb.data(forType: .rtf), rtf.count < 2_000_000 { d.rtf = rtf }
            if let html = pb.data(forType: .html), html.count < 2_000_000 { d.html = html }
            draft = d
        }
        guard var d = draft else { return }
        d.sourceBundle = bundle
        d.sourceName = front?.localizedName ?? ""
        store.insert(d)
    }

    private static func pngData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private func imageDraft(_ png: Data) -> ClipDraft? {
        guard let rep = NSBitmapImageRep(data: png) else { return nil }
        let hash = ClipDraft.hash(png)
        let path = imagesDir.appendingPathComponent(hash + ".png")
        if !FileManager.default.fileExists(atPath: path.path) {
            try? png.write(to: path)
            if let thumb = Self.thumbnail(rep, maxSide: 96) { try? thumb.write(to: Self.thumbURL(path)) }
        }
        var d = ClipDraft(kind: .image, text: "", hash: hash, imagePath: path.path)
        d.width = rep.pixelsWide; d.height = rep.pixelsHigh; d.bytes = png.count
        return d
    }

    private static func thumbnail(_ rep: NSBitmapImageRep, maxSide: CGFloat) -> Data? {
        let w = CGFloat(rep.pixelsWide), h = CGFloat(rep.pixelsHigh)
        let k = min(1, maxSide / max(w, h))
        let size = NSSize(width: max(1, w * k), height: max(1, h * k))
        let img = NSImage(size: size)
        img.lockFocus()
        rep.draw(in: NSRect(origin: .zero, size: size))
        img.unlockFocus()
        guard let tiff = img.tiffRepresentation else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    static func thumbURL(_ png: URL) -> URL { png.deletingPathExtension().appendingPathExtension("thumb.png") }

    // MARK: retention / deletion

    func purge() {
        let s = Settings.shared.data
        let day: TimeInterval = 86_400
        let paths = store.purge(
            textBefore: s.clipboardTextDays > 0 ? Date().addingTimeInterval(-Double(s.clipboardTextDays) * day) : nil,
            imagesBefore: s.clipboardImageDays > 0 ? Date().addingTimeInterval(-Double(s.clipboardImageDays) * day) : nil)
        paths.forEach(removeImage)
    }

    func removeImage(_ path: String) {
        try? FileManager.default.removeItem(atPath: path)
        try? FileManager.default.removeItem(at: Self.thumbURL(URL(fileURLWithPath: path)))
    }

    func clearAll() { store.clear().forEach(removeImage) }

    // MARK: paste

    /// Replaces the pasteboard (ignored by the watcher). If `paste`, sends ⌘V to the frontmost app.
    /// `clearAfter`: wipe the pasteboard after N seconds (only if nothing else was copied meanwhile) and mark
    /// the content concealed so other clipboard managers skip it. Used for secrets.
    /// `thenReturn`: press Return after pasting (run a pasted terminal command).
    func write(paste: Bool, clearAfter: TimeInterval? = nil, thenReturn: Bool = false, _ fill: (NSPasteboard) -> Void) {
        let pb = NSPasteboard.general
        pb.clearContents()
        fill(pb)
        if let clearAfter {
            pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
            let mine = pb.changeCount
            DispatchQueue.main.asyncAfter(deadline: .now() + clearAfter) { [weak self] in
                guard NSPasteboard.general.changeCount == mine else { return }
                NSPasteboard.general.clearContents()
                self?.ownWrites.insert(NSPasteboard.general.changeCount)
            }
        }
        ownWrites.insert(pb.changeCount)
        guard paste else { return }
        if !AXIsProcessTrusted() {
            if !askedForAccessibility {
                askedForAccessibility = true
                AXIsProcessTrustedWithOptions([kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary)
            }
            return // content is on the clipboard; user can ⌘V once Accessibility is granted
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
            if thenReturn {
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
                    for down in [true, false] { CGEvent(keyboardEventSource: src, virtualKey: 36, keyDown: down)?.post(tap: .cghidEventTap) }
                }
            }
        }
    }
}
